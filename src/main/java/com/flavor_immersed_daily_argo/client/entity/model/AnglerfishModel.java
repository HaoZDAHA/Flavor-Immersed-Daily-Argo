	@Override
	public ModelPart root() {
		return this.bone;
	}

	@Override
	public void setupAnim(Anglerfish entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
// 恢复默认姿势，避免上一帧动画残留
		this.root().getAllParts().forEach(ModelPart::resetPose);

// 鮟鱇鱼只有一段循环游动动画
		entity.swimAnimationState.startIfStopped(entity.tickCount);
		this.animate(entity.swimAnimationState, animation, ageInTicks, 1.0F);
	}
