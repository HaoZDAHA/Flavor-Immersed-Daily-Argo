	@Override
	public void setupAnim(Lobster entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
// 恢复默认姿势，避免上一帧动画残留
		this.root().getAllParts().forEach(ModelPart::resetPose);

		if (entity.isInWater()) {
// 水中：循环播放 lobster_swim
			entity.idleAnimationState.stop();
			entity.walkAnimationState.stop();
			entity.swimAnimationState.startIfStopped(entity.tickCount);
			this.animate(entity.swimAnimationState, lobster_swim, ageInTicks, 1.0F);
		} else if (limbSwingAmount > 0.05F) {
// 陆地爬行：播放单次动画 lobster_go
			entity.idleAnimationState.stop();
			entity.swimAnimationState.stop();
			entity.walkAnimationState.startIfStopped(entity.tickCount);
			this.animate(entity.walkAnimationState, lobster_go, ageInTicks, 1.0F);
		} else {
// 静止：循环播放 lobster_no
			entity.swimAnimationState.stop();
			entity.walkAnimationState.stop();
			entity.idleAnimationState.startIfStopped(entity.tickCount);
			this.animate(entity.idleAnimationState, lobster_no, ageInTicks, 1.0F);
		}
	}
