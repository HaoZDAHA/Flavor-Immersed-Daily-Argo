	public static LayerDefinition createBodyLayer() {
		MeshDefinition meshdefinition = new MeshDefinition();
		PartDefinition partdefinition = meshdefinition.getRoot();

		PartDefinition bone = partdefinition.addOrReplaceChild("bone", CubeListBuilder.create(), PartPose.offset(0.0F, 24.0F, -3.0F));

		PartDefinition tail = bone.addOrReplaceChild("tail", CubeListBuilder.create().texOffs(18, 20).addBox(1.0F, -3.0F, 2.0F, 0.0F, 3.0F, 5.0F, new CubeDeformation(0.0F))
		.texOffs(0, 13).addBox(0.0F, -3.0F, -5.0F, 2.0F, 3.0F, 7.0F, new CubeDeformation(0.0F)), PartPose.offset(-1.0F, 0.0F, 10.0F));

		PartDefinition head = bone.addOrReplaceChild("head", CubeListBuilder.create().texOffs(18, 13).addBox(0.0F, -3.0F, -4.0F, 2.0F, 3.0F, 4.0F, new CubeDeformation(0.0F))
		.texOffs(0, 23).addBox(0.0F, -3.0F, -6.0F, 2.0F, 2.0F, 2.0F, new CubeDeformation(0.0F)), PartPose.offset(-1.0F, 0.0F, -1.0F));

		PartDefinition body = bone.addOrReplaceChild("body", CubeListBuilder.create().texOffs(4, 4).addBox(-1.0F, -3.0F, -4.0F, 2.0F, 3.0F, 6.0F, new CubeDeformation(0.0F)), PartPose.offset(0.0F, 0.0F, 3.0F));

		return LayerDefinition.create(meshdefinition, 32, 32);
	}

	@Override
	public ModelPart root() {
		return this.bone;
	}

	@Override
	public void setupAnim(JapaneseHalfbeak entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
// 恢复默认姿势，避免上一帧动画残留
		this.root().getAllParts().forEach(ModelPart::resetPose);

// 马步鱼只有一段循环游动动画
		entity.swimAnimationState.startIfStopped(entity.tickCount);
		this.animate(entity.swimAnimationState, japanese_halfbeak_swim, ageInTicks, 1.0F);
	}
