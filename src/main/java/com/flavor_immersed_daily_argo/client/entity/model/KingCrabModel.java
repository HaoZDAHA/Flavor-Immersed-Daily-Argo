	@Override
	public void setupAnim(KingCrab entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
// 恢复默认姿势，避免上一帧动画残留
		this.root().getAllParts().forEach(ModelPart::resetPose);

// go = 行走动画（水中游动 / 陆地爬行）；no = 闲置动画（循环）
		if (entity.isInWater() || limbSwingAmount > 0.05F) {
			entity.idleAnimationState.stop();
			entity.swimAnimationState.startIfStopped(entity.tickCount);
			this.animate(entity.swimAnimationState, kingcrab_go, ageInTicks, 1.0F);
		} else {
			entity.swimAnimationState.stop();
			entity.idleAnimationState.startIfStopped(entity.tickCount);
			this.animate(entity.idleAnimationState, kingcrab_no, ageInTicks, 1.0F);
		}
	}
