	@Override
	public void setupAnim(HairyCrab entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
// 恢复默认姿势，避免上一帧动画残留
		this.root().getAllParts().forEach(ModelPart::resetPose);

		if (entity.isInWater() || limbSwingAmount > 0.05F) {
			entity.idleAnimationState.stop();
			entity.swimAnimationState.startIfStopped(entity.tickCount);
			this.animate(entity.swimAnimationState, hairy_crab_go, ageInTicks, 1.0F);
		} else {
			entity.swimAnimationState.stop();
			entity.idleAnimationState.startIfStopped(entity.tickCount);
			this.animate(entity.idleAnimationState, hairy_crab_no, ageInTicks, 1.0F);
		}
	}
