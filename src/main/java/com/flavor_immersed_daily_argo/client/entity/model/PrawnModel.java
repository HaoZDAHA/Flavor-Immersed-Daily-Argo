	@Override
	public ModelPart root() {
		return this.bone;
	}

	@Override
	public void setupAnim(Prawn entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
		this.root().getAllParts().forEach(ModelPart::resetPose);

		if (limbSwingAmount > 0.05F) {
			entity.idleAnimationState.stop();
			entity.swimAnimationState.startIfStopped(entity.tickCount);
			this.animate(entity.swimAnimationState, prawn_go, ageInTicks, 1.0F);
		} else {
			entity.swimAnimationState.stop();
			entity.idleAnimationState.startIfStopped(entity.tickCount);
			this.animate(entity.idleAnimationState, prawn_no, ageInTicks, 1.0F);
		}
	}
