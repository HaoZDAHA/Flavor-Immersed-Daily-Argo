	@Override
	public void setupAnim(Turtle entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
// 恢复默认姿势，避免上一帧动画残留
		this.root().getAllParts().forEach(ModelPart::resetPose);

		if (entity.isInWater()) {
			entity.idleAnimationState.stop();
			entity.moveAnimationState.stop();
			entity.swimAnimationState.startIfStopped(entity.tickCount);
			this.animate(entity.swimAnimationState, turtle_swim, ageInTicks, 1.0F);
		} else if (limbSwingAmount > 0.05F) {
			entity.idleAnimationState.stop();
			entity.swimAnimationState.stop();
			entity.moveAnimationState.startIfStopped(entity.tickCount);
			this.animate(entity.moveAnimationState, turtle_go, ageInTicks, 1.0F);
		} else {
			entity.swimAnimationState.stop();
			entity.moveAnimationState.stop();
			entity.idleAnimationState.startIfStopped(entity.tickCount);
			this.animate(entity.idleAnimationState, turtle_no, ageInTicks, 1.0F);
		}
	}
